/// 인증 관련 고정값(P46).
abstract final class AuthConfig {
  /// 스토어 심사용 계정 번호(E.164) — **가공 번호다.**
  ///
  /// 010-0000-0000은 국내 이동통신에 할당되지 않는 대역이라 실제 가입자가 없고,
  /// Firebase 콘솔의 "테스트 전화번호"로 등록하면 **실제 SMS가 발송되지 않는다**
  /// (할당량도 소모하지 않는다). 심사자는 이 번호 + 고정 코드로 즉시 로그인한다.
  ///
  /// 이 값이 코드에 박히는 것이 안전한 이유: 이 번호로 로그인해도 볼 수 있는 것은
  /// **심사용으로 만든 회원 한 명의 데이터**뿐이다(어드민에서 그 회원을 등록해야
  /// 비로소 홈이 열린다 — 등록 안 하면 "회원 정보를 찾지 못했어요"로 끝난다).
  /// 실제 회원의 정보에는 어떤 경로로도 닿지 않는다.
  ///
  /// **셋업 2단계**(둘 다 해야 동작한다 — store/README.md 제출 순서 참조):
  ///   ① Firebase 콘솔 > Authentication > 로그인 방법 > 전화 > 테스트 전화번호에
  ///      `+82 10-0000-0000` / 코드 `000000` 등록
  ///   ② 어드민 > 회원 관리에서 전화번호 `010-0000-0000`으로 회원 등록
  ///      (회원권·예약·기록이 있어야 심사자가 앱 기능을 볼 수 있다)
  static const reviewPhoneE164 = '+821000000000';

  /// 심사자 안내용 국내 표기 — 스토어 심사 노트에 적는 값과 같아야 한다.
  static const reviewPhoneDisplay = '010-0000-0000';

  /// 고정 인증코드(Firebase 콘솔에 등록하는 값과 같아야 한다).
  static const reviewCode = '000000';
}
