/// 반경 토큰 — 목업의 `border-radius`를 역할별로 묶은 것.
///
/// **간격(`AppSpacing`)은 일부러 없다.** 예전엔 4/8/12/16/24 5단 스케일이 선언돼
/// 있었지만 참조가 0회였다. 이 앱의 여백은 디자인 스케일이 아니라 목업 CSS의 px를
/// 1:1로 옮긴 값이라, 실측 분포가 2·3·4·5·6·8·9·10·12·14·16·18·20·26으로 거의
/// 연속이다 — 5단으로 흡수하려면 렌더가 바뀌고(= 리팩터가 아니라 디자인 변경),
/// 값마다 이름을 붙이면 스케일이 아니라 그냥 별칭표가 된다. 어느 쪽도 이득이
/// 없어서 **삭제**했다. 안 쓰는 스케일을 남겨두면 다음 사람이 "이게 우리 시스템"
/// 이라고 읽고 잘못 쓰거나, 지금처럼 또 무시한다.
///
/// 반경은 반대다: 실제로 12곳에서 참조되고 값이 역할별로 뚜렷하게 갈린다.
/// 목업 근거가 있는 일회성 값(카메라 래퍼 16 · 코멘트 박스 9 · 세그먼트 안쪽 8 ·
/// 수평계 눈금 2)은 토큰으로 올리지 않고 호출부에 남긴다 — 재사용되지 않는 값에
/// 이름을 붙이면 토큰 목록이 실제 시스템보다 커 보인다.
///
/// 여백을 다시 토큰화하려면 목업 자체를 스케일에 맞춰 다시 그리는 게 먼저다.
abstract final class AppRadius {
  static const chip = 10.0;
  static const card = 14.0;
  static const button = 10.0;
  static const pill = 999.0;
}
