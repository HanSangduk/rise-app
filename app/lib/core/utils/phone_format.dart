/// 한국 휴대폰 번호 → E.164(+82) 정규화 — Firebase Phone Auth 입력 형식이자,
/// 로컬 대기 기록(JoinRequestStore) 대조에 쓰는 키.
///
/// **판단은 백엔드 `domain.NormalizePhone`(backend/internal/domain/phone.go)과
/// 같아야 한다.** 그쪽이 "같은 번호인가"의 단일 진실이기 때문이다: 앱이 이 값으로
/// 로그인하면 Firebase ID 토큰에 그대로 실려 가고, 백엔드는 그 번호와 어드민이
/// 저장한 국내 표기("010-1234-5678")를 각각 정규화해 대조한다. 여기서 다른 결론을
/// 내면 같은 사람이 영원히 매칭되지 않고, 기존 회원이 가입 요청으로 흘러가
/// 중복 레코드가 된다.
///
/// 백엔드는 비교 키를 **국내 표기**("01012345678")로, 앱은 Firebase가 요구하는
/// **E.164**("+821012345678")로 뽑는다 — 표기만 다르고 판단은 같다:
///
/// | 입력                | 백엔드 키      | 이 함수         |
/// |---------------------|----------------|-----------------|
/// | `010-1234-5678`     | `01012345678`  | `+821012345678` |
/// | `+82 10-1234-5678`  | `01012345678`  | `+821012345678` |
/// | `+8201012345678`    | `01012345678`  | `+821012345678` | ← 0을 안 지운 오입력
/// | `1012345678`        | `01012345678`  | `+821012345678` | ← 엑셀에서 선행 0 유실
/// | `+82 2 123 4567`    | `021234567`    | `+8221234567`   |
/// | `15881234`          | `15881234`     | `15881234`      | ← 둘 다 손대지 않는다
///
/// 마지막 줄이 예전 구현과 갈리던 지점이다. 예전엔 0도 82도 아닌 입력을 **전부**
/// `+82{digits}`로 만들었다 — 백엔드가 "판단 근거가 없어 손대지 않는다"고 정한
/// 자리에 앱이 없는 국가코드를 지어내 붙인 것이라, 두 계층이 서로 다른 번호를
/// 말하게 된다. 여기서도 근거가 없으면 만들지 않는다(길이 검증이 먼저 걸러내고,
/// 그래도 남으면 Firebase가 invalid-phone-number로 거절해 사용자에게 알린다).
String normalizeKoreanPhone(String input) {
  final trimmed = input.trim();
  final digits = trimmed.replaceAll(RegExp(r'[^0-9]'), '');

  // ① 한국 국가코드 82. '+' 유무는 보지 않는다 — 국내 표기는 이동전화·지역번호 모두
  //    0으로 시작하므로(010/02/031), 숫자열이 82로 시작하면 국가코드다(백엔드 주석).
  //    남은 부분이 이미 0으로 시작하면 "+8201012345678" 같은 흔한 오입력이다.
  if (digits.length > 2 && digits.startsWith('82')) {
    final rest = digits.substring(2);
    return rest.startsWith('0') ? '+82${rest.substring(1)}' : '+82$rest';
  }

  // ② 국내 표기 — 선행 0을 국가코드로 바꾼다.
  if (digits.startsWith('0')) return '+82${digits.substring(1)}';

  // ③ 엑셀 숫자 셀에서 선행 0이 떨어진 명단("1012349999"). 0 없이 "10"으로 시작하는
  //    10자리는 "010 휴대폰에서 0이 빠진 것" 말고 존재하지 않는다 — 백엔드와 동일하게
  //    딱 여기까지만 복원한다(9자리 지역번호 추측은 남의 번호에 매칭될 수 있다).
  if (digits.length == 10 && digits.startsWith('10')) return '+82$digits';

  // ④ 그 밖 — 백엔드가 손대지 않는 입력. 한국 번호로 단정할 근거가 없으므로
  //    +82를 지어내지 않는다. 다만 사용자가 **직접 '+'를 붙인** 국제번호는 그 의도가
  //    명시적이니 그대로 살린다(비교 키는 백엔드도 숫자만 남겨 같은 결론이 된다).
  if (trimmed.startsWith('+')) return '+$digits';
  return digits;
}

/// 화면 표시용 하이픈 포맷 — `01012345678` → `010-1234-5678`.
///
/// 정규화([normalizeKoreanPhone])와 목적이 다르다: 그쪽은 서버와 대조할 **키**를 만들고,
/// 이건 사람에게 보여줄 **표기**를 만든다. 사용자가 숫자만 입력해도 안내 문구는 입력란의
/// 힌트(`010-1234-5678`)와 같은 모양이어야 한다 — 실기기 점검에서 "01012345678로 보냈어요"가
/// 그대로 노출되는 걸 발견해 추가했다(P09).
///
/// 국내 휴대폰(11자리 01X) · 서울(02) · 그 외 지역번호(10자리)를 다룬다.
/// 규칙에 맞지 않으면 **원본을 그대로 돌려준다** — 모르는 형식을 억지로 끊어 더 읽기 어렵게
/// 만들지 않는다.
String formatKoreanPhoneForDisplay(String raw) {
  final d = raw.replaceAll(RegExp(r'[^0-9]'), '');
  if (d.length == 11 && d.startsWith('01')) {
    return '${d.substring(0, 3)}-${d.substring(3, 7)}-${d.substring(7)}';
  }
  if (d.length == 10 && d.startsWith('02')) {
    return '${d.substring(0, 2)}-${d.substring(2, 6)}-${d.substring(6)}';
  }
  if (d.length == 10 && d.startsWith('0')) {
    return '${d.substring(0, 3)}-${d.substring(3, 6)}-${d.substring(6)}';
  }
  return raw;
}
