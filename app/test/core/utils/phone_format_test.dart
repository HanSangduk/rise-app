import 'package:flutter_test/flutter_test.dart';
import 'package:rise_member/core/utils/phone_format.dart';

// normalizeKoreanPhone은 백엔드 domain.NormalizePhone(backend/internal/domain/phone.go)과
// **같은 판단**을 해야 한다. 앱이 이 값으로 Firebase에 로그인하면 그 번호가 그대로
// ID 토큰에 실려 가고, 백엔드는 그 번호와 어드민이 저장한 국내 표기를 각자 정규화해
// 대조한다. 판단이 갈리면 같은 사람이 영원히 매칭되지 않는다.
//
// 표기만 다르다: 백엔드는 국내 표기("01012345678"), 앱은 E.164("+821012345678").
// 아래 테스트는 "무엇을 복원하고 무엇은 손대지 않는가"의 경계를 고정한다.
void main() {
  group('국내 표기 → E.164', () {
    test('하이픈 입력 "010-1234-5678" → "+821012345678"', () {
      expect(normalizeKoreanPhone('010-1234-5678'), '+821012345678');
    });

    test('숫자만 "01012345678" → "+821012345678"', () {
      expect(normalizeKoreanPhone('01012345678'), '+821012345678');
    });

    test('공백 포함 "010 5555 6666" → "+821055556666"', () {
      expect(normalizeKoreanPhone('010 5555 6666'), '+821055556666');
    });

    test('앞뒤 공백은 무시', () {
      expect(normalizeKoreanPhone('  010-1234-5678  '), '+821012345678');
    });

    test('지역번호도 같은 규칙 — "02-123-4567" → "+8221234567"', () {
      // 백엔드: "+82 2 123 4567" → "021234567". 같은 번호로 수렴한다.
      expect(normalizeKoreanPhone('02-123-4567'), '+8221234567');
    });
  });

  group('국가코드 82 — + 유무를 가리지 않는다', () {
    test('"+82 10-1234-5678" → "+821012345678"', () {
      expect(normalizeKoreanPhone('+82 10-1234-5678'), '+821012345678');
    });

    test('+ 없는 국가코드 "8210 1234 5678" → "+821012345678"', () {
      expect(normalizeKoreanPhone('8210 1234 5678'), '+821012345678');
    });

    test('"+8201012345678"(0을 안 지운 흔한 오입력) → "+821012345678"', () {
      // 예전엔 '+'로 시작하면 숫자만 남겨 그대로 돌려줘서 "+8201012345678"이 됐다.
      // Firebase 토큰의 번호와도, 백엔드 키("01012345678")와도 어긋나는 값이다.
      expect(normalizeKoreanPhone('+8201012345678'), '+821012345678');
    });

    test('10자리 "8212345678"도 국가코드로 본다 → "+8212345678"', () {
      // 국내 표기는 이동전화·지역번호 모두 0으로 시작하므로, 82로 시작하는 숫자열은
      // 국가코드가 붙은 것이다(길이로 갈릴 문제가 아니다). 백엔드: "012345678".
      // 예전 구현은 "11자리 이상일 때만 국가코드"라 "+828212345678"을 만들었다.
      expect(normalizeKoreanPhone('8212345678'), '+8212345678');
    });

    test('"82"만 있으면 국가코드로 치지 않는다(뒤가 비었다)', () {
      // 백엔드도 rest가 비면 손대지 않는다.
      expect(normalizeKoreanPhone('82'), '82');
    });
  });

  group('선행 0 복원 — 딱 "10"으로 시작하는 10자리까지만', () {
    test('엑셀 숫자 셀에서 0이 떨어진 "1012345678" → "+821012345678"', () {
      expect(normalizeKoreanPhone('1012345678'), '+821012345678');
    });

    test('9자리는 복원하지 않는다 — 지역번호인지 갈리지 않는다', () {
      // 추측해서 붙이면 남의 번호에 매칭될 수 있다(백엔드 주석과 동일한 이유).
      expect(normalizeKoreanPhone('212345678'), '212345678');
    });

    test('"10" 시작이어도 11자리면 복원하지 않는다', () {
      expect(normalizeKoreanPhone('10123456789'), '10123456789');
    });
  });

  group('근거가 없으면 +82를 지어내지 않는다', () {
    test('대표번호 "1588-1234"는 그대로 — 원래 0으로 시작하지 않는 정상 표기', () {
      // 예전엔 "+8215881234"가 나왔다. 백엔드는 "15881234"로 두므로 두 계층이
      // 서로 다른 번호를 말하게 된다.
      expect(normalizeKoreanPhone('1588-1234'), '15881234');
    });

    test('빈 입력은 빈 문자열 — "+82"라는 유령 번호를 만들지 않는다', () {
      expect(normalizeKoreanPhone(''), '');
      expect(normalizeKoreanPhone('   '), '');
    });

    test('사용자가 직접 붙인 국제번호(+1…)는 그 의도대로 살린다', () {
      // 백엔드 키도 숫자만 남긴 "14155551234"라 대조 결과는 같다.
      expect(normalizeKoreanPhone('+1 415-555-1234'), '+14155551234');
    });
  });

  group('Firebase 토큰 번호와의 왕복 — 대기 기록 대조가 깨지지 않는다', () {
    test('E.164를 다시 정규화해도 값이 변하지 않는다(멱등)', () {
      // JoinRequestStore는 정규화한 값을 저장하고, 복원 때 Firebase가 준
      // user.phoneNumber를 다시 정규화해 대조한다 — 멱등이 아니면 대기 카드를 잃는다.
      for (final input in ['010-1234-5678', '+82 10 1234 5678', '1012345678']) {
        final once = normalizeKoreanPhone(input);
        expect(normalizeKoreanPhone(once), once, reason: input);
        expect(once, '+821012345678', reason: input);
      }
    });
  });
}
