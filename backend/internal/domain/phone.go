package domain

import "strings"

// NormalizePhone — 전화번호 비교용 정규화. 3계층이 서로 다른 표기로 같은 번호를 말하기 때문에
// 존재한다: 어드민은 사람이 읽는 국내 표기("010-1234-5678")로 저장하고, 앱의 Firebase ID
// 토큰은 E.164("+821012345678")로만 번호를 싣는다(P06 — 토큰 번호가 진실 원천).
// 숫자만 남기는 단순 비교는 이 둘을 영원히 불일치시킨다(01012345678 ≠ 821012345678).
//
// 규칙: 숫자만 남긴 뒤, 한국 국가코드 82로 시작하면 제거하고 국내 표기의 선행 0을 복원한다.
// 국내 표기는 이동전화·지역번호 모두 0으로 시작하므로("010", "02", "031"), 숫자열이 82로
// 시작한다는 것은 국가코드가 붙었다는 뜻이라 오인 위험이 없다.
//
//	"+82 10-1234-5678" → "01012345678"   (E.164 이동전화)
//	"010-1234-5678"    → "01012345678"   (국내 표기 — 같은 값으로 수렴)
//	"+82 2 123 4567"   → "021234567"     (E.164 지역번호)
//	"+8201012345678"   → "01012345678"   (0을 지우지 않은 흔한 오입력)
//	"1012345678"       → "01012345678"   (엑셀 숫자 셀에서 선행 0이 떨어진 회원 명단)
//
// 반환값은 저장용이 아니라 **비교 키**다. 원본 표기는 그대로 보존한다(어드민 화면 가독성).
func NormalizePhone(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if r >= '0' && r <= '9' {
			b.WriteRune(r)
		}
	}
	digits := b.String()

	if rest, ok := strings.CutPrefix(digits, "82"); ok && rest != "" {
		if strings.HasPrefix(rest, "0") {
			return rest // "+8201012345678" 같은 오입력 — 이미 국내 표기.
		}
		return "0" + rest
	}

	// 엑셀에서 옮긴 명단 복구: 전화번호가 숫자 셀로 저장되면 선행 0이 사라져 "1012349999"로
	// 들어온다. 그러면 같은 사람인데 저장값은 "1012349999", 토큰(+821012349999)은 "01012349999"로
	// 정규화돼 영원히 매칭되지 않고 — 기존 회원이 가입 요청으로 흘러가 대표가 승인하면 중복
	// 레코드가 생긴다(패스·이력은 옛 레코드에 남은 채로). 국내 표기는 이동전화·지역번호 모두
	// 0으로 시작하므로, 0 없이 "10"으로 시작하는 10자리 숫자열은 "010 휴대폰에서 0이 떨어진 것"
	// 말고는 존재하지 않는다.
	//
	// 여기까지만 좁게 본다. 9자리(예: "212345678" → "02-1234-5678"?)는 지역번호 복원인지 다른
	// 표기인지 갈리지 않아 추측하면 남의 번호에 매칭될 수 있고, 8자리 대표번호("15881234")는
	// 애초에 0으로 시작하지 않는 정상 표기다 — 둘 다 손대지 않는다.
	if len(digits) == 10 && strings.HasPrefix(digits, "10") {
		return "0" + digits
	}
	return digits
}
