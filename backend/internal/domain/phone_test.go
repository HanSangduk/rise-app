package domain

import "testing"

// P06 회귀: Firebase ID 토큰의 E.164 번호와 어드민이 저장한 국내 표기가 같은 키로 수렴해야
// 한다. 이게 깨지면 앱 회원의 가입 매칭(join/match·confirm)이 프로덕션에서 전부 실패한다.
func TestNormalizePhone(t *testing.T) {
	cases := []struct{ in, want string }{
		{"010-1234-5678", "01012345678"},    // 어드민 저장 표기(사람이 읽는 형태)
		{"+821012345678", "01012345678"},    // Firebase 토큰 phone_number
		{"+82 10-1234-5678", "01012345678"}, // 공백 섞인 E.164
		{"01012345678", "01012345678"},      // 하이픈 없는 국내 표기
		{"+8201012345678", "01012345678"},   // 국가코드 뒤 0을 남긴 오입력
		{"+82 2 123 4567", "021234567"},     // 지역번호(서울) E.164
		{"02-123-4567", "021234567"},        // 지역번호 국내 표기
		{"", ""},                            // 빈 값은 빈 키(호출부가 미입력으로 거른다)
		{"---", ""},                         // 숫자 없음
		{"82", "82"},                        // 국가코드만 — 자를 나머지가 없으면 원본 유지

		// 엑셀 숫자 셀에서 선행 0이 떨어진 명단 — 복원한다.
		{"1012349999", "01012349999"},   // 회원 명단 이관 사고의 실제 모양
		{"10 1234 9999", "01012349999"}, // 구분자가 섞여도 숫자열 기준은 같다

		// 복원하면 **안 되는** 인접 입력 — 좁은 규칙의 경계.
		{"0212345678", "0212345678"},   // 10자리지만 0으로 시작(02-1234-5678) — 이미 국내 표기
		{"1112345678", "1112345678"},   // 10자리 "11" 시작 — "10"이 아니면 추측하지 않는다
		{"212345678", "212345678"},     // 9자리 — 지역번호 복원은 모호해서 손대지 않는다
		{"15881234", "15881234"},       // 대표번호 8자리 — 0으로 시작하지 않는 정상 표기
		{"1012345", "1012345"},         // "10" 시작이지만 7자리 — 휴대폰 길이가 아니다
		{"10123456789", "10123456789"}, // 11자리 — 0이 떨어진 휴대폰이라면 10자리여야 한다
	}
	for _, c := range cases {
		if got := NormalizePhone(c.in); got != c.want {
			t.Errorf("NormalizePhone(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

// 토큰 표기와 저장 표기가 반드시 같은 키로 만나는지 — 위 표의 핵심 쌍을 명시적으로 못박는다.
func TestNormalizePhoneTokenMatchesStored(t *testing.T) {
	token, stored := "+821012345678", "010-1234-5678"
	if NormalizePhone(token) != NormalizePhone(stored) {
		t.Fatalf("토큰(%s)과 저장 번호(%s)가 불일치 — 가입 매칭이 막힌다", token, stored)
	}
}

// 엑셀 이관 회귀: 숫자 셀로 저장돼 선행 0이 날아간 번호도 토큰과 같은 키로 만나야 한다.
// 안 만나면 이미 있는 회원이 가입 요청으로 흘러가고, 승인 시 중복 레코드가 생긴다
// (패스·이력은 옛 레코드에 남아 어느 쪽도 온전하지 않다).
func TestNormalizePhoneRestoresExcelDroppedZero(t *testing.T) {
	token, stored := "+821012349999", "1012349999"
	if NormalizePhone(token) != NormalizePhone(stored) {
		t.Fatalf("토큰(%s)과 엑셀 저장 번호(%s)가 불일치 — 중복 회원이 생긴다", token, stored)
	}
	// 반대 방향 오매칭 금지: 복원 규칙이 서로 다른 번호를 같은 키로 묶으면 안 된다.
	if NormalizePhone("1012349999") == NormalizePhone("1112349999") {
		t.Fatal("서로 다른 번호가 같은 키로 수렴 — 남의 레코드에 매칭된다")
	}
}
